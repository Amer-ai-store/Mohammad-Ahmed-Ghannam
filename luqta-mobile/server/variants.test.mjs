import test from "node:test";
import assert from "node:assert/strict";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { resolve } from "node:path";
import { createCommerceServer } from "./commerce.mjs";

test("SKU variants have independent stock and parent cannot be purchased", async (t) => {
  const directory = await mkdtemp(resolve(tmpdir(), "luqta-variants-"));
  const password = "variant-test-password-123";
  const app = await createCommerceServer({ dbPath: resolve(directory, "store.sqlite"), bootstrapAdmin: { name: "مدير", email: "admin@example.test", password } });
  await new Promise((done) => app.server.listen(0, "127.0.0.1", done));
  t.after(async () => { await app.close(); await rm(directory, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${app.server.address().port}/api`;
  const request = async (method, path, body, token) => {
    const response = await fetch(base + path, { method, headers: { ...(body === undefined ? {} : { "Content-Type": "application/json" }), ...(token ? { Authorization: `Bearer ${token}` } : {}) }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
    return { status: response.status, body: await response.json() };
  };
  const admin = (await request("POST", "/auth/login", { email: "admin@example.test", password })).body;
  const customer = (await request("POST", "/auth/register", { name: "عميل", email: "buyer@example.test", password })).body;
  const parent = { id: "shirt", name: "قميص", category: "fashion", price: 20, stock: 9 };
  assert.equal((await request("POST", "/admin/products", parent, admin.token)).status, 201);
  assert.equal((await request("POST", "/admin/products", { id: "missing-blue", name: "قميص", category: "fashion", price: 12, stock: 1, variantOf: "missing", variantLabel: "أزرق" }, admin.token)).status, 400);
  assert.equal((await request("POST", "/admin/products", { id: "shirt-blue", name: "قميص", category: "fashion", price: 12, stock: 1, variantOf: "shirt", variantLabel: "أزرق / M" }, admin.token)).status, 201);
  assert.equal((await request("POST", "/admin/products", { id: "shirt-red", name: "قميص", category: "fashion", price: 15, stock: 2, variantOf: "shirt", variantLabel: "أحمر / L" }, admin.token)).status, 201);
  assert.equal((await request("POST", "/admin/products", { id: "nested", name: "قميص", category: "fashion", price: 11, stock: 1, variantOf: "shirt-blue", variantLabel: "صغير" }, admin.token)).status, 400);
  const displayed = (await request("GET", "/products/shirt")).body.product;
  assert.equal(displayed.hasVariants, true);
  assert.equal(displayed.stock, 3);
  assert.equal(displayed.price, 12);
  assert.equal(displayed.baseStock, 9);
  const address = { name: "عميل", phone: "+962790123456", city: "عمان", street: "شارع الاختبار 12" };
  const place = (items, idempotencyKey) => request("POST", "/orders", { items, address, paymentMethod: "cod", idempotencyKey }, customer.token);
  assert.equal((await place([{ productId: "shirt", quantity: 1 }], "parent-variant-rejected")).body.code, "variant_required");
  assert.equal((await place([{ productId: "shirt-blue", quantity: 2 }], "blue-overstock")).body.code, "out_of_stock");
  const created = await place([{ productId: "shirt-blue", quantity: 1 }, { productId: "shirt-red", quantity: 1 }], "variants-checkout-one");
  assert.equal(created.status, 201, JSON.stringify(created.body));
  assert.equal(created.body.order.subtotal, 27);
  assert.match(created.body.order.items[0].name, /أزرق/);
  assert.equal((await request("GET", "/products/shirt-blue")).body.product.stock, 0);
  assert.equal((await request("GET", "/products/shirt-red")).body.product.stock, 1);
  assert.equal((await request("GET", "/products/shirt")).body.product.stock, 1);
  assert.equal((await place([{ productId: "shirt-blue", quantity: 1 }], "blue-second-attempt")).body.code, "out_of_stock");
  assert.equal((await request("POST", `/orders/${created.body.order.id}/cancel`, {}, customer.token)).status, 200);
  assert.equal((await request("GET", "/products/shirt")).body.product.stock, 3);
  assert.equal((await request("DELETE", "/admin/products/shirt", {}, admin.token)).status, 200);
  const catalog = (await request("GET", "/products")).body.products;
  assert.ok(!catalog.some((product) => ["shirt", "shirt-blue", "shirt-red"].includes(product.id)));
});
