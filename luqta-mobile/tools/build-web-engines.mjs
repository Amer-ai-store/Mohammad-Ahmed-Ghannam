// Packs three.js (MIT, r149) and the Luqta WebGL engines into a TS module of
// strings so the WebView/iframe can run fully offline from the app bundle.
// Run: node tools/build-web-engines.mjs [path/to/three.min.js]
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const vendored = join(root, 'web-engines', 'vendor', 'three.r149.min.js');
const threePath = process.argv[2] || vendored;
if (!existsSync(threePath)) throw new Error(`three.min.js not found at ${threePath}`);
const three = readFileSync(threePath, 'utf8');
if (!three.includes('REVISION="149"') && !three.includes("REVISION='149'") && !/REVISION\s*=\s*"149"/.test(three)) {
  if (!three.includes('"149"')) throw new Error('Expected three.js revision 149');
}
if (threePath !== vendored) writeFileSync(vendored, three);
const avatar = readFileSync(join(root, 'web-engines', 'avatar.js'), 'utf8');
const viewer = readFileSync(join(root, 'web-engines', 'viewer.js'), 'utf8');
// GLTFLoader + SkeletonUtils (three r149 examples/jsm, MIT) pre-bundled as an IIFE that
// attaches to window.THREE, plus the embedded placeholder character (rigged, skinned GLB).
const gltf = readFileSync(join(root, 'web-engines', 'vendor', 'three.r149.gltf-loader.min.js'), 'utf8');
if (!gltf.includes('GLTFLoader')) throw new Error('GLTFLoader bundle missing');
const modelPath = join(root, 'assets', 'character', 'placeholder-xbot.glb');
const model = readFileSync(modelPath);
if (model.readUInt32LE(0) !== 0x46546c67) throw new Error('placeholder model is not a GLB');
const modelB64 = model.toString('base64');
const lit = (s) => JSON.stringify(s).replace(/[\u2028\u2029]/g, (c) => (c === '\u2028' ? '\\u2028' : '\\u2029'));
const sha = (s) => createHash('sha256').update(s).digest('hex').slice(0, 16);
const out = `// GENERATED by tools/build-web-engines.mjs — do not edit by hand.
// three.js r149 © 2010-2023 three.js authors, MIT License.
export const ENGINE_VERSION = ${JSON.stringify(`three-r149:${sha(three)}|avatar:${sha(avatar)}|viewer:${sha(viewer)}|gltf:${sha(gltf)}|model:${sha(model)}`)};
export const THREE_JS = ${lit(three)};
export const AVATAR_JS = ${lit(avatar)};
export const VIEWER_JS = ${lit(viewer)};
export const GLTF_JS = ${lit(gltf)};
`;
writeFileSync(join(root, 'src', 'components', 'character', 'webEngines.generated.ts'), out);
const modelOut = `// GENERATED by tools/build-web-engines.mjs — do not edit by hand.
// Placeholder rigged character (Mixamo X Bot, skinned mesh + skeleton + clips). Replace it by
// setting the dashboard setting "characterModelUrl" to your own GLB, or by swapping
// assets/character/placeholder-xbot.glb and re-running the generator.
export const CHARACTER_MODEL_SHA = ${JSON.stringify(sha(model))};
export const CHARACTER_MODEL_BYTES = ${model.length};
export const CHARACTER_MODEL_DATA_URL = ${JSON.stringify('data:model/gltf-binary;base64,' + modelB64)};
`;
writeFileSync(join(root, 'src', 'components', 'character', 'characterModel.generated.ts'), modelOut);
console.log('engines packed', sha(three), sha(avatar), sha(viewer), sha(gltf), `${(out.length / 1024).toFixed(0)} KiB`, 'model', sha(model), `${(modelOut.length / 1024).toFixed(0)} KiB`);
